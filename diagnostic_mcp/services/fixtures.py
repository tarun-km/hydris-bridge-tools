"""Stub read-only plant data standing in for Lite's real read-service
layer (see docs/scope.md). A real deployment replaces only this module
(plus services/scoring.py, which is derived from it) - every tool in
tools/ goes through the same records, and no mutating method exists here
or anywhere in this package (BRIDGE-1, SAFE-1, DATA-1).

Two factories, matching the exact grant fixtures the source docs name
(u-ops-alpha -> fx-mbr-01 only, u-ops-beta -> fx-beta-01 only,
services/grants.py::seeded_grant_store):

- fx-mbr-01 (Alpha MBR Plant 01, food_and_beverage): an equalization tank
  feeding a membrane bioreactor. Its story over the 30-day fixture window
  is a slow membrane-fouling arc - TMP climbing, flux declining - that
  eventually correlates with an effluent COD exceedance, so tools 4
  through 8 all have something coherent to say about the same underlying
  event when a caller (or an LLM) walks the arc from score to alert to
  compliance.
- fx-beta-01 (Beta Effluent Plant 01, textiles): an equalization tank
  feeding an activated-sludge basin, mostly stable, with a milder SVI
  trend climbing toward a bulking watch threshold. Everything else stays
  in-band and effluent stays compliant, so this factory reads as the
  "quiet" contrast case.

All series are generated by deterministic closed-form functions of the
day index (see _tmp_series etc. below) rather than random sampling or
hand-typed literals, so the same fixture always produces the same
numbers - the whole point of a "deterministic explanation of why a score
is what it is" ([PRD] Sec 3.1) falls apart if the underlying data isn't
reproducible too.
"""

