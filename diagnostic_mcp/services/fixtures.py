@dataclass(frozen=True)
class AlertRecord:
    alert_id: str
    factory_id: str
    unit_id: str | None
    parameter_code: str | None
    rule_name: str
    severity: Literal["info", "warning", "critical"]
    fired_at: str
    status: Literal["active", "resolved"]
