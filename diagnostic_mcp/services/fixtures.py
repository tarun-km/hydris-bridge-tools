# ---------------------------------------------------------------------------
# Deterministic series generators
# ---------------------------------------------------------------------------


def _stable(n: int, center: float, amplitude: float, freq: float, decimals: int = 2) -> list[float]:
    return [round(center + amplitude * math.sin(i * freq), decimals) for i in range(n)]


def _tmp_series(n: int = HISTORY_DAYS) -> list[float]:
    """Stable ~21-23 kPa for the first two weeks, then a fouling-style ramp
    up to ~42 kPa - crosses the watch band (>30 kPa) around day 20."""
    values = []
    for i in range(n):
        if i <= 14:
            base = 22 + math.sin(i * 0.6) * 1.2
        else:
            progress = (i - 14) / (n - 1 - 14)
            base = 22 + progress * 20 + math.sin(i * 0.6) * 0.8
        values.append(round(base, 1))
    return values


def _flux_series(n: int = HISTORY_DAYS) -> list[float]:
    """Inversely correlated with TMP - declining flux is the other face of
    the same fouling event, crossing the watch band (<15 LMH) in the same
    window TMP crosses its own."""
    values = []
    for i in range(n):
        if i <= 14:
            base = 24 + math.sin(i * 0.5) * 0.8
        else:
            progress = (i - 14) / (n - 1 - 14)
            base = 24 - progress * 10 + math.sin(i * 0.5) * 0.5
        values.append(round(base, 1))
    return values


def _svi_series(n: int = HISTORY_DAYS) -> list[float]:
    """Stable ~110 mL/g for three weeks, then a milder climb toward the
    bulking watch threshold (150 mL/g), reaching ~165 by the last day."""
    values = []
    for i in range(n):
        if i <= 19:
            base = 110 + math.sin(i * 0.4) * 6
        else:
            progress = (i - 19) / (n - 1 - 19)
            base = 110 + progress * 55 + math.sin(i * 0.4) * 4
        values.append(round(base, 0))
    return values


