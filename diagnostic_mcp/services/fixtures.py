def get_plant_record(factory_id: str) -> PlantRecord | None:
    return _PLANTS.get(factory_id)


def get_unit_record(factory_id: str, unit_id: str) -> UnitRecord | None:
    plant = get_plant_record(factory_id)
    if plant is None:
        return None
    return next((u for u in plant.units if u.unit_id == unit_id), None)


def get_parameter_series(
    factory_id: str, unit_id: str, parameter_code: str
) -> list[tuple[str, float]] | None:
    return PARAMETER_SERIES.get((factory_id, unit_id, parameter_code))


def get_band(parameter_code: str) -> ParameterBand | None:
    return PARAMETER_BANDS.get(parameter_code)


def get_plant_record_or_raise(factory_id: str) -> PlantRecord:
    """A granted factory_id with no backing record is a data-consistency
    bug (the grant store and the fixture store have drifted), not a
    caller error - authorization already passed by the time any handler
    calls this. Shared by every tool that only needs the plant record
    (plant_overview, current_scores, active_alerts, compliance_status)
    so the same LookupError message isn't hand-copied per tool.
    """
    record = get_plant_record(factory_id)
    if record is None:
        raise LookupError(f"No plant record for granted factory_id={factory_id!r}")
    return record


def get_unit_record_or_raise(factory_id: str, unit_id: str) -> UnitRecord:
    """unit_id isn't itself a security scope (factory_id already carried
    that check via BRIDGE-2), so naming it back to the caller doesn't leak
    anything - unlike an unknown/ungranted factory_id, this is an
    ordinary bad-argument error. Shared by unit_detail, explain_score and
    parameter_history.
    """
    unit = get_unit_record(factory_id, unit_id)
    if unit is None:
        raise LookupError(f"No unit {unit_id!r} for factory {factory_id!r}.")
    return unit


def resolve_as_of(as_of_date: str | None) -> str:
    """Resolve an optional caller-supplied as_of date, defaulting to the
    latest date this fixture set holds.

    Raises ValueError if the caller-supplied date falls outside the range
    this fixture set actually has data for. Silently scoring an
    out-of-range date would otherwise produce contributions=[] and a
    fabricated health_score=100 (see services/scoring.py::score_unit) -
    indistinguishable from a genuinely healthy plant, which is exactly
    the "assume good data" failure BRIDGE-9 exists to prevent elsewhere
    in this codebase (get_parameter_history's record_status). Used by
    get_current_scores and explain_score, the two tools that take an
    as_of_date.
    """
    if as_of_date is None:
        return FIXTURE_TODAY.isoformat()
    parsed = date.fromisoformat(as_of_date)
    if not (EARLIEST_DATE <= parsed <= FIXTURE_TODAY):
        raise ValueError(
            f"as_of_date {as_of_date!r} is outside the range this fixture set holds "
            f"data for ({EARLIEST_DATE.isoformat()} to {FIXTURE_TODAY.isoformat()})."
        )
    return as_of_date


